export const hrQuizMaxScore = hrQuizQuestions.length * 3;

export const scoreQuiz = (answers: number[]): number =>
  answers.reduce((sum, optIdx, qIdx) => sum + (hrQuizQuestions[qIdx]?.options[optIdx]?.score ?? 0), 0);

export const resultIndexFor = (score: number): number =>
  hrQuizResults.findIndex((r) => score >= r.min && score <= r.max);
