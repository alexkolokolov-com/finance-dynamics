const classify = (n: number, y: number, l: number) => {
  if (n < 45) return "manual";
  if (y < 55) return "month";
  if (l < 60) return "year";
  return "life";
};

/**
 * Интерактивная диагностика финансового горизонта: 12 вопросов,
 * реакция на каждый ответ и итоговый профиль с тремя шкалами.
 */
export const HorizonQuiz = () => {
  const [started, setStarted] = useState(false);
  const [index, setIndex] = useState(0);
  const [picked, setPicked] = useState<(number | null)[]>(Array(questions.length).fill(null));
  const [done, setDone] = useState(false);

  const q = questions[index];
  const current = picked[index];

  const scoreOf = (axis: Axis) => {
    const total = questions.reduce(
      (sum, question, i) =>
        question.axis === axis && picked[i] !== null
          ? sum + question.answers[picked[i] as number][1]
          : sum,
      0
    );
    const max = questions.filter((question) => question.axis === axis).length * 3;
    return Math.round((total / max) * 100);
  };

  const pick = (i: number) => {
    setPicked((prev) => prev.map((value, j) => (j === index ? i : value)));
  };

  const next = () => {
    if (current === null) return;
    if (index + 1 < questions.length) setIndex(index + 1);
    else setDone(true);
  };

  const now = scoreOf("now");
  const year = scoreOf("year");
  const life = scoreOf("life");
  const profile = profiles[classify(now, year, life)];

  return (
    <div className="container-px max-w-3xl mx-auto">
      <div className="bg-card border border-border rounded-2xl p-6 md:p-10">
        {!started ? (
          <>
            <p className="font-body text-sm text-accent">
              {nbsp("Диагностика")}
            </p>
            <h3 className="mt-3 font-display font-semibold leading-[1.15] tracking-tight text-[clamp(1.4rem,3vw,2rem)]">
              {nbsp("Где заканчивается ваш финансовый горизонт?")}
            </h3>
            <p className="mt-4 font-body text-lg leading-relaxed text-foreground/80">
              {nbsp(
                "Мы начнём с ближайших недель и постепенно будем отодвигаться: месяц, несколько месяцев, год, пять лет, пенсия. В какой-то момент ответы обычно становятся менее определёнными. Вот этот момент и интересен."
              )}
            </p>
            <p className="mt-3 font-body text-sm text-foreground/60">
              {nbsp("12 вопросов. Баллы считать не нужно.")}
            </p>
            <button
              type="button"
              onClick={() => setStarted(true)}
              className="mt-6 inline-flex items-center justify-center px-7 py-4 rounded-full bg-accent text-background font-body text-[15px] font-medium hover:bg-foreground transition-colors"
            >
              {nbsp("Начать")}
            </button>
          </>
        ) : !done ? (
          <>
            <div className="flex items-center justify-between gap-4 font-body text-[13px] text-foreground/60">
              <span>{nbsp(`Вопрос ${index + 1} из ${questions.length}`)}</span>
              <span>{nbsp(q.time)}</span>
            </div>
            <div className="mt-3 h-1 rounded-full bg-border overflow-hidden">
              <div
                className="h-full bg-accent transition-all duration-500"
                style={{ width: `${((index + (current === null ? 0 : 1)) / questions.length) * 100}%` }}
              />
            </div>

            <h3 className="mt-6 font-display font-semibold leading-[1.18] tracking-tight text-[clamp(1.25rem,2.6vw,1.75rem)]">
              {nbsp(q.title)}
            </h3>
            <p className="mt-3 font-body text-[15px] leading-relaxed text-foreground/65">
              {nbsp(q.note)}
            </p>

            <div className="mt-5 grid gap-2.5">
              {q.answers.map((answer, i) => (
                <button
                  key={answer[0]}
                  type="button"
                  onClick={() => pick(i)}
                  className={`text-left font-body text-[15px] leading-snug rounded-xl border px-4 py-3.5 transition-colors ${
                    current === i
                      ? "border-accent bg-accent/10 text-foreground"
                      : "border-border bg-background text-foreground/85 hover:border-foreground/40"
                  }`}
                >
                  {nbsp(answer[0])}
                </button>
              ))}
            </div>

            {current !== null ? (
              <>
                <p className="mt-4 rounded-xl bg-background border border-border px-4 py-3.5 font-body text-[15px] leading-relaxed text-foreground/75">
                  {nbsp(q.answers[current][2])}
                </p>
                <div className="mt-4 flex justify-end">
                  <button
                    type="button"
                    onClick={next}
                    className="font-body text-[15px] font-medium text-accent hover:text-foreground transition-colors"
                  >
                    {index + 1 < questions.length ? nbsp("Дальше →") : nbsp("Показать результат →")}
                  </button>
                </div>
              </>
            ) : null}
          </>
        ) : (
          <>
            <p className="font-body text-sm text-accent">
              {nbsp("Результат")}
            </p>
            <h3 className="mt-3 font-display font-semibold leading-[1.12] tracking-tight text-[clamp(1.5rem,3.4vw,2.2rem)]">
              {nbsp(profile.title)}
            </h3>
            <p className="mt-4 font-body text-lg leading-relaxed text-foreground/80">
              {nbsp(profile.lead)}
            </p>

            <div className="mt-7 grid gap-4">
              {([["now", now], ["year", year], ["life", life]] as [Axis, number][]).map(
                ([axis, value]) => (
                  <div key={axis}>
                    <div className="flex items-center justify-between font-body text-[13px] font-medium text-foreground/75">
                      <span>{nbsp(axisLabels[axis])}</span>
                      <span>{value}%</span>
                    </div>
                    <div className="mt-1.5 h-2 rounded-full bg-border overflow-hidden">
                      <div
                        className="h-full bg-accent transition-all duration-700"
                        style={{ width: `${value}%` }}
                      />
                    </div>
                  </div>
                )
              )}
            </div>

            <div className="mt-7 border-t border-b border-border py-5">
              <p className="font-body text-[13px] text-foreground/60">
                {nbsp("Где система начинает слабеть")}
              </p>
              <h4 className="mt-2 font-display font-semibold text-xl leading-snug">
                {nbsp(profile.blind[0])}
              </h4>
              <p className="mt-2 font-body text-[15px] leading-relaxed text-foreground/75">
                {nbsp(profile.blind[1])}
              </p>
            </div>

            <h4 className="mt-7 font-display font-semibold text-xl leading-snug">
              {nbsp("Что делать дальше")}
            </h4>
            <div className="mt-4 grid gap-4">
              {profile.actions.map(([title, text], i) => (
                <div key={title} className="grid grid-cols-[28px_1fr] gap-3 items-start">
                  <span className="w-7 h-7 rounded-lg bg-foreground text-background font-body text-xs font-semibold grid place-items-center">
                    {i + 1}
                  </span>
                  <span className="font-body text-[15px] leading-relaxed text-foreground/75">
                    <strong className="block text-foreground font-medium">{nbsp(title)}</strong>
                    {nbsp(text)}
                  </span>
                </div>
              ))}
            </div>

            <div className="mt-8 flex flex-col sm:flex-row sm:items-center gap-4">
              <a
                href="https://nivz.getcourse.ru/diagnostic_article3"
                target="_blank"
                rel="noopener noreferrer"
                onClick={handleDiagnosticClick}
                className="inline-flex items-center justify-center px-7 py-4 rounded-full bg-accent text-background font-body text-[15px] font-medium hover:bg-foreground transition-colors"
              >
                {nbsp("Разобрать мой горизонт на диагностике")}
              </a>
              <button
                type="button"
                onClick={() => {
                  setPicked(Array(questions.length).fill(null));
                  setIndex(0);
                  setDone(false);
                  setStarted(false);
                }}
                className="font-body text-[15px] text-foreground/60 hover:text-foreground transition-colors"
              >
                {nbsp("Пройти заново")}
              </button>
            </div>
          </>
        )}
      </div>
    </div>
  );
};
